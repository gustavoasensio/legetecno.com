function translatePage(lang) {
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[key] && translations[key][lang]) {
            el.innerHTML = translations[key][lang];
        }
    });
}

let currentLang = localStorage.getItem('lang') || 'es';
translatePage(currentLang);

// Language toggle
const langToggle = document.getElementById('langToggle');
if (langToggle) {
    langToggle.addEventListener('click', () => {
        currentLang = currentLang === 'es' ? 'en' : 'es';
        localStorage.setItem('lang', currentLang);
        translatePage(currentLang);
    });
}

// Hamburger menu
const hamburger = document.getElementById('hamburger');
const mainNav = document.getElementById('mainNav');
if (hamburger && mainNav) {
    hamburger.addEventListener('click', () => {
        const isOpen = mainNav.classList.toggle('nav-open');
        hamburger.classList.toggle('active', isOpen);
        hamburger.setAttribute('aria-expanded', String(isOpen));
    });

    mainNav.querySelectorAll('a').forEach(link => {
        link.addEventListener('click', () => {
            mainNav.classList.remove('nav-open');
            hamburger.classList.remove('active');
            hamburger.setAttribute('aria-expanded', 'false');
        });
    });
}

// Scroll-in animation
if ('IntersectionObserver' in window) {
    const observer = new IntersectionObserver(
        entries => entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('visible');
                observer.unobserve(entry.target);
            }
        }),
        { threshold: 0.12 }
    );
    document.querySelectorAll('.fade-in').forEach(el => observer.observe(el));
} else {
    document.querySelectorAll('.fade-in').forEach(el => el.classList.add('visible'));
}

// ─── Formspree endpoint ───────────────────────────────────────────────────────
// 1. Creá una cuenta gratuita en https://formspree.io
// 2. Creá un nuevo formulario apuntando a gustavoasensio@gmail.com
// 3. Reemplazá YOUR_FORM_ID con el ID que te da Formspree (ej: xyzabc12)
const FORMSPREE_URL = 'https://formspree.io/f/mbdbdqkk';
// ─────────────────────────────────────────────────────────────────────────────

const contactForm = document.getElementById('contactForm');
const formSuccess = document.getElementById('formSuccess');
const formError   = document.getElementById('formError');

function validateField(input) {
    const errorEl = input.parentElement.querySelector('.field-error');
    if (!input.value.trim()) {
        input.classList.add('error');
        if (errorEl) errorEl.textContent = translations.contact_form_error_required[currentLang];
        return false;
    }
    if (input.type === 'email') {
        const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
        if (!emailRegex.test(input.value.trim())) {
            input.classList.add('error');
            if (errorEl) errorEl.textContent = translations.contact_form_error_email[currentLang];
            return false;
        }
    }
    input.classList.remove('error');
    if (errorEl) errorEl.textContent = '';
    return true;
}

if (contactForm) {
    contactForm.querySelectorAll('input, textarea').forEach(field => {
        field.addEventListener('blur', () => validateField(field));
        field.addEventListener('input', () => {
            if (field.classList.contains('error')) validateField(field);
        });
    });

    contactForm.addEventListener('submit', async e => {
        e.preventDefault();

        const fields = [...contactForm.querySelectorAll('input, textarea')];
        if (!fields.every(f => validateField(f))) return;

        const submitBtn = contactForm.querySelector('[type="submit"]');
        submitBtn.disabled = true;
        submitBtn.textContent = translations.contact_form_sending[currentLang];

        try {
            const res = await fetch(FORMSPREE_URL, {
                method: 'POST',
                headers: { 'Accept': 'application/json', 'Content-Type': 'application/json' },
                body: JSON.stringify({
                    name:    document.getElementById('name').value,
                    email:   document.getElementById('email').value,
                    message: document.getElementById('message').value
                })
            });

            if (res.ok) {
                contactForm.style.display = 'none';
                if (formSuccess) formSuccess.hidden = false;
                if (formError)   formError.hidden   = true;
            } else {
                throw new Error('server');
            }
        } catch {
            submitBtn.disabled = false;
            submitBtn.textContent = translations.contact_form_submit[currentLang];
            if (formError) {
                formError.querySelector('p').textContent = translations.contact_form_error_send[currentLang];
                formError.hidden = false;
            }
        }
    });
}
